-- Scoped to the 9264000..9264999 key range so only this case's rows are asserted.
SELECT
    MORBIDITY_REPORT_KEY,
    MORBIDITY_REPORT_LOCAL_ID,
    JURISDICTION_NAME,
    PATIENT_LOCAL_ID,
    PROVIDER_LAST_NAME,
    REPORTER_LAST_NAME,
    REPORT_FAC_NAME,
    REPORTING_FACILITY_UID,
    HOSPITAL_FAC_NAME,
    INVESTIGATION_KEY,
    INVESTIGATION_CREATED_IND,
    CASE_STATUS,
    PROGRAM_AREA_DESCRIPTION,
    EXTERNAL_IND
FROM RDB_MODERN.dbo.MORBIDITY_REPORT_DATAMART
WHERE MORBIDITY_REPORT_KEY BETWEEN 9264000 AND 9264999
ORDER BY MORBIDITY_REPORT_KEY;
