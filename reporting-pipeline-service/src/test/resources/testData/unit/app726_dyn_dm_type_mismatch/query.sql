SELECT
    (SELECT COUNT(*)
     FROM RDB_MODERN.dbo.job_flow_log
     WHERE package_name = 'sp_dyn_dm_createdm_postprocessing: APP726'
       AND status_type = 'ERROR'
       AND error_description LIKE '%Operand type clash%') AS OPERAND_TYPE_CLASH_COUNT,
    (SELECT COUNT(*)
     FROM RDB_MODERN.dbo.job_flow_log
     WHERE package_name = 'sp_dyn_dm_createdm_postprocessing: APP726'
       AND status_type = 'COMPLETE') AS COMPLETE_COUNT,
    (SELECT data_type
     FROM RDB_MODERN.INFORMATION_SCHEMA.COLUMNS
     WHERE table_name = 'DM_INV_APP726'
       AND column_name = 'SRC_FLOAT') AS SRC_FLOAT_TYPE,
    (SELECT data_type
     FROM RDB_MODERN.INFORMATION_SCHEMA.COLUMNS
     WHERE table_name = 'DM_INV_APP726'
       AND column_name = 'SRC_DT2') AS SRC_DT2_TYPE,
    (SELECT data_type
     FROM RDB_MODERN.INFORMATION_SCHEMA.COLUMNS
     WHERE table_name = 'DM_INV_APP726'
       AND column_name = 'SRC_DTO') AS SRC_DTO_TYPE,
    (SELECT data_type
     FROM RDB_MODERN.INFORMATION_SCHEMA.COLUMNS
     WHERE table_name = 'DM_INV_APP726'
       AND column_name = 'SRC_TM') AS SRC_TM_TYPE,
    (SELECT data_type
     FROM RDB_MODERN.INFORMATION_SCHEMA.COLUMNS
     WHERE table_name = 'DM_INV_APP726'
       AND column_name = 'SRC_NVC') AS SRC_NVC_TYPE,
    (SELECT data_type
     FROM RDB_MODERN.INFORMATION_SCHEMA.COLUMNS
     WHERE table_name = 'DM_INV_APP726'
       AND column_name = 'SRC_BIN') AS SRC_BIN_TYPE,
    (SELECT CAST(SRC_FLOAT AS VARCHAR(20))
     FROM RDB_MODERN.dbo.DM_INV_APP726
     WHERE INVESTIGATION_KEY = 1) AS SRC_FLOAT_VALUE,
    (SELECT CONVERT(VARCHAR(27), SRC_DT2, 126)
     FROM RDB_MODERN.dbo.DM_INV_APP726
     WHERE INVESTIGATION_KEY = 1) AS SRC_DT2_VALUE,
    (SELECT CONVERT(VARCHAR(40), SRC_DTO, 127)
     FROM RDB_MODERN.dbo.DM_INV_APP726
     WHERE INVESTIGATION_KEY = 1) AS SRC_DTO_VALUE,
    (SELECT CONVERT(VARCHAR(16), SRC_TM, 114)
     FROM RDB_MODERN.dbo.DM_INV_APP726
     WHERE INVESTIGATION_KEY = 1) AS SRC_TM_VALUE,
    (SELECT SRC_NVC
     FROM RDB_MODERN.dbo.DM_INV_APP726
     WHERE INVESTIGATION_KEY = 1) AS SRC_NVC_VALUE,
    (SELECT CONVERT(VARCHAR(20), SRC_BIN, 1)
     FROM RDB_MODERN.dbo.DM_INV_APP726
     WHERE INVESTIGATION_KEY = 1) AS SRC_BIN_VALUE;